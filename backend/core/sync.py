def apply_temperature(*, organization, device, payload, occurred_at, performed_by):
    """A buffered batch of sensor readings.

    Each reading is idempotent on its own timestamp, so a re-sent buffer
    overlapping one already received adds nothing.
    """
    from datetime import datetime

    from inventory.telemetry import Sensor, record_reading

    sensor = Sensor.objects.filter(
        organization=organization, device_code=payload["sensor"]
    ).first()
    if sensor is None:
        raise DomainError(
            f"Unknown sensor '{payload['sensor']}'.", code="unknown_sensor"
        )

    stored = 0
    excursions = 0
    for entry in payload.get("readings", []):
        result = record_reading(
            sensor=sensor,
            celsius=entry["celsius"],
            recorded_at=datetime.fromisoformat(entry["at"]),
            # Anything replayed through sync was held on the device.
            was_buffered=True,
            performed_by=performed_by,
        )
        if not result.duplicate:
            stored += 1
        if result.opened:
            excursions += 1

    return {"stored": stored, "excursions_opened": excursions}


def apply_sale(*, organization, device, payload, occurred_at, performed_by):
    """A sale journalled while the connection was down.

    Rebuilt through the ordinary service path rather than inserted: an
    offline sale must meet the same prescription gate, the same FEFO
    allocation and the same controlled register as one rung up live.
    Trusting the device's own totals would make the offline path the way
    to bypass every rule.
    """
    from catalog.models import Product, UnitOfMeasure
    from inventory.models import Location
    from sales import payments, services as sales

    location = Location.objects.get(organization=organization, pk=payload["location"])
    branch = location.branch
    if branch is None:
        raise DomainError(
            f"{location.name} is not attached to a branch.", code="location_has_no_branch"
        )

    sale = sales.start_sale(
        organization=organization,
        branch=branch,
        location=location,
        cashier=performed_by,
    )
    sale.occurred_at = occurred_at
    sale.save(update_fields=["occurred_at"])

    for line in payload.get("lines", []):
        product = Product.objects.get(organization=organization, pk=line["product"])
        sales.add_line(
            sale=sale,
            product=product,
            quantity=line["quantity"],
            uom=UnitOfMeasure.objects.get(product=product, code=line["uom_code"]),
            unit_price=line["unit_price"],
            discount=line.get("discount", 0),
        )

    # Tender before posting. Money changed hands at the till during the
    # outage; a sale replayed without it would sit in PENDING_PAYMENT and
    # day end would report a shortfall that does not exist.
    for tender in payload.get("payments", []):
        payments.take_payment(
            sale=sale,
            method=tender["method"],
            amount=int(tender["amount"]),
            performed_by=performed_by,
            provider_code=tender.get("provider", ""),
            phone=tender.get("phone", ""),
        )

    sales.complete_sale(
        sale=sale,
        performed_by=performed_by,
        idempotency_key=payload.get("client_id", ""),
    )
    return {"sale": str(sale.id), "number": sale.number, "status": sale.status}


def apply_stock_count(*, organization, device, payload, occurred_at, performed_by):
    """A stocktake done on the floor, with the difference as a movement.

    The count itself is not the record — the adjustment is. Writing a
    counted figure straight into a balance would be the one thing the
    ledger exists to prevent.
    """
    from core.quantity import from_base
    from inventory import services as inventory
    from inventory.models import Batch, Location, MovementKind

    location = Location.objects.get(organization=organization, pk=payload["location"])
    adjustments = 0

    for entry in payload.get("counts", []):
        batch = Batch.objects.get(organization=organization, pk=entry["batch"])
        on_hand = inventory.balance_for(
            organization=organization, product=batch.product, location=location
        )
        difference = int(entry["counted_base"]) - on_hand
        if difference == 0:
            continue
        inventory.post_movement(
            organization=organization,
            location=location,
            batch=batch,
            kind=MovementKind.ADJUSTMENT,
            quantity=from_base(difference, batch.product.base_uom),
            performed_by=performed_by,
            reason=entry.get("reason", "Stock count"),
        )
        adjustments += 1

    return {"adjustments": adjustments}
